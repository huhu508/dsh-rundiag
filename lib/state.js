// Serialize writes so the 10-minute sync timer and client saves never interleave.
let writeChain = Promise.resolve()
export function persist(state) {
  const snapshot = JSON.stringify(state, null, 2)
  writeChain = writeChain.catch(() => {}).then(async () => {
    const file = stateFile()
    await mkdir(path.dirname(file), { recursive: true })
    const temp = `${file}.${process.pid}.${Date.now()}.tmp`
    await writeFile(temp, snapshot, 'utf8')
    try {
      await copyFile(file, `${file}.bak`)
    } catch (error) {
      if (error?.code !== 'ENOENT') console.warn('[dsh-rundiag] could not refresh the backup:', error?.message || error)
    }
    await rename(temp, file)
    try {
      await access(`${file}.bak`)
    } catch {
      try {
        await copyFile(file, `${file}.bak`)
      } catch (error) {
        console.warn('[dsh-rundiag] could not create the initial backup:', error?.message || error)
      }
    }
  })
  return writeChain
}

export function mergeClientState(state, payload) {
  const body = payload && typeof payload === 'object' ? payload : {}
  if (Array.isArray(body.tasks)) state.tasks = sanitizeTasks(body.tasks)
  if (Array.isArray(body.reviews)) state.reviews = sanitizeReviews(body.reviews)
  if (typeof body.integrations?.coros?.autoSync === 'boolean') {
    state.integrations.coros.autoSync = body.integrations.coros.autoSync
  }
  if (typeof body.integrations?.coros?.autoCreateTasks === 'boolean') {
    state.integrations.coros.autoCreateTasks = body.integrations.coros.autoCreateTasks
  }
  state.revision += 1
  state.updatedAt = nowIso()
  recomputeParents(state.tasks)
  return state
}

export function recomputeParents(tasks) {
  const byParent = new Map()
  for (const task of tasks) {
    if (!task.parentId) continue
    if (!byParent.has(task.parentId)) byParent.set(task.parentId, [])
    byParent.get(task.parentId).push(task)
  }
  const visit = (task, depth = 0) => {
    if (depth > 30) return task.completed
    const children = byParent.get(task.id) || []
    if (!children.length) return task.completed
    const done = children.every((child) => visit(child, depth + 1))
    if (done !== task.completed) {
      task.completed = done
      task.completedAt = done ? (task.completedAt || nowIso()) : null
    }
    return done
  }
  for (const task of tasks) visit(task)
  return tasks
}

function matchesTask(task, activity) {
  if (task.autoGenerated || !task.autoSync?.enabled || task.completed) return false
  if (task.autoSync.sport !== 'all' && task.autoSync.sport !== activity.sport) return false
  const start = task.startDate || task.dueDate
  const end = task.dueDate || task.startDate
  if (!start && !end) return false
  if (start && activity.date < start) return false
  if (end && activity.date > end) return false
  if (task.autoSync.keyword) {
    const keyword = task.autoSync.keyword.toLowerCase()
    if (!String(activity.name || '').toLowerCase().includes(keyword)) return false
  }
  return true
}

function progressDelta(task, activity) {
  if (task.progress.mode === 'distance') return Math.round(activity.distanceKm * 100) / 100
  if (task.progress.mode === 'duration') return Math.round(activity.durationMin)
  return 1
}

function activityIso(activity) {
  const raw = String(activity.startTime || '').trim()
  if (!raw) return ''
  const numeric = Number(raw)
  if (Number.isFinite(numeric) && numeric > 0) {
    return new Date(numeric > 1e12 ? numeric : numeric * 1000).toISOString()
  }
  const parsed = Date.parse(raw)
  return Number.isFinite(parsed) ? new Date(parsed).toISOString() : ''
}

function autoProgress(distance, duration) {
  if (distance > 0) return { mode: 'distance', current: distance, target: distance, unit: 'km' }
  if (duration > 0) return { mode: 'duration', current: duration, target: duration, unit: '分钟' }
  return { mode: 'check', current: 1, target: 1, unit: '' }
}

function autoTitle(label, distance, duration) {
  if (distance > 0) return `今日${label} · ${distance.toFixed(2)} km`
  if (duration > 0) return `今日${label} · ${Math.round(duration)} 分钟`
  return `今日${label}`
}

function autoNotes(label, activities, distance, duration) {
  const lines = activities.slice(0, 30).map((activity) => {
    const bits = []
    if (activity.distanceKm > 0) bits.push(`${activity.distanceKm.toFixed(2)} km`)
    if (activity.durationMin > 0) bits.push(`${Math.round(activity.durationMin)} 分钟`)
    if (!bits.length) bits.push('已完成')
    return `· ${activity.name || label}：${bits.join(' / ')}`
  })
  if (activities.length > 30) lines.push(`· 另有 ${activities.length - 30} 条活动`)
  const totals = []
  if (distance > 0) totals.push(`${distance.toFixed(2)} km`)
  if (duration > 0) totals.push(`${Math.round(duration)} 分钟`)
  return `由 COROS 自动补齐\n\n${lines.join('\n')}\n\n合计：${totals.join(' / ') || '已完成'}`
}

function applyGeneratedTasks(state, today) {
  const coros = state.integrations.coros
  if (coros.autoCreateTasks === false) return { created: 0, updated: 0 }
  // COROS 训练记录是客观数据，不能通过删除任务把当天的数据球藏掉。
  coros.dismissedAutoTasks = []
  for (const task of state.tasks) {
    if (task.absorbedBy && !state.tasks.some((row) => row.id === task.absorbedBy)) task.absorbedBy = ''
  }
  const taskById = new Map(state.tasks.map((task) => [task.id, task]))
  const groups = new Map()
  for (const activity of state.activities) {
    if (activity.date !== today) continue
    const sourceKey = `coros:${today}:${activity.sport}`
    const matchedManual = (activity.matchedTaskIds || []).some((id) => {
      const task = taskById.get(id)
      return task && !task.autoGenerated
    })
    if (matchedManual) continue
    if (!groups.has(sourceKey)) groups.set(sourceKey, [])
    groups.get(sourceKey).push(activity)
  }

  let created = 0
  let updated = 0
  for (const [sourceKey, group] of groups) {
    const sport = group[0].sport
    const label = sportLabel(sport)
    const distance = roundMetric(group.reduce((sum, activity) => sum + Number(activity.distanceKm || 0), 0))
    const duration = Math.round(group.reduce((sum, activity) => sum + Number(activity.durationMin || 0), 0))
    const latest = group.map(activityIso).filter(Boolean).sort().at(-1) || nowIso()
    const title = autoTitle(label, distance, duration)
    const notes = autoNotes(label, group, distance, duration)
    const progress = autoProgress(distance, duration)
    const totalMinutes = group.reduce((sum, activity) => sum + (Number(activity.durationMin) || 0), 0)
    const weightedHr = totalMinutes > 0
      ? Math.round(group.reduce((sum, activity) => sum + (Number(activity.avgHr) || 0) * (Number(activity.durationMin) || 0), 0) / totalMinutes)
      : 0
    const actual = sanitizeActual({
      distanceKm: distance,
      durationMin: duration,
      avgHr: weightedHr,
      maxHr: group.reduce((max, activity) => Math.max(max, Number(activity.maxHr) || 0), 0),
      calories: group.reduce((sum, activity) => sum + (Number(activity.calories) || 0), 0),
      trainingLoad: group.reduce((sum, activity) => sum + (Number(activity.trainingLoad) || 0), 0),
      elevationGain: group.reduce((sum, activity) => sum + (Number(activity.elevationGain) || 0), 0),
      elevationLoss: group.reduce((sum, activity) => sum + (Number(activity.elevationLoss) || 0), 0),
      avgPower: group.reduce((max, activity) => Math.max(max, Number(activity.avgPower) || 0), 0),
      normalizedPower: group.reduce((max, activity) => Math.max(max, Number(activity.normalizedPower) || 0), 0),
      sport,
      startTime: group.map(activityIso).filter(Boolean).sort()[0] || '',
      name: group[0]?.name || label,
      activityIds: group.map((activity) => activity.id)
    })
    let task = state.tasks.find((row) => row.autoGenerated && row.sourceKey === sourceKey)
    if (!task) {
      const top = state.tasks
        .filter((row) => !row.parentId)
        .reduce((min, row) => Math.min(min, Number(row.order) || 0), 0)
      task = {
        id: uid('task'),
        title,
        notes,
        parentId: null,
        dueDate: today,
        startDate: '',
        priority: 2,
        category: 'training',
        tags: ['COROS', label],
        completed: true,
        completedAt: latest,
        createdAt: nowIso(),
        updatedAt: nowIso(),
        order: top - 1,
        progress,
        actual,
        autoGenerated: true,
        sourceKey,
        sourceDate: today,
        sourceSport: sport,
        autoSync: { enabled: false, sport, keyword: '' }
      }
      state.tasks.push(task)
      created += 1
    } else {
      if (!String(task.title || '').startsWith('今日')) {
        // Preserve a custom title the user chose after the task was generated.
      } else {
        task.title = title
      }
      task.notes = notes
      task.dueDate = today
      task.progress = progress
      task.actual = actual
      task.category = 'training'
      task.completed = true
      task.completedAt = task.completedAt || latest
      task.tags = [...new Set([...(task.tags || []), 'COROS', label])].slice(0, 12)
      task.autoGenerated = true
      task.sourceKey = sourceKey
      task.sourceDate = today
      task.sourceSport = sport
      task.autoSync = { enabled: false, sport, keyword: '' }
      task.updatedAt = nowIso()
      updated += 1
    }
    for (const activity of group) {
      if (!activity.matchedTaskIds.includes(task.id)) activity.matchedTaskIds.push(task.id)
    }
  }
  return { created, updated }
}

export function applyDailyMetrics(state, incoming) {
  const rows = Array.isArray(incoming) ? incoming : []
  const known = new Map(state.dailyMetrics.map((row) => [row.date, row]))
  let added = 0
  let updated = 0
  for (const raw of rows) {
    const metric = sanitizeDailyMetric(raw)
    if (!metric) continue
    const existing = known.get(metric.date)
    if (existing) {
      const merged = { ...existing }
      for (const [key, value] of Object.entries(metric)) {
        if ((value !== 0 && value !== '') || existing[key] === undefined) merged[key] = value
      }
      Object.assign(existing, merged)
      updated += 1
    } else {
      state.dailyMetrics.push(metric)
      known.set(metric.date, metric)
      added += 1
    }
  }
  state.dailyMetrics.sort((a, b) => a.date.localeCompare(b.date))
  if (state.dailyMetrics.length > MAX_METRICS) state.dailyMetrics = state.dailyMetrics.slice(-MAX_METRICS)
  return { added, updated }
}

function mergeActual(task, activity) {
  const prev = task.actual && typeof task.actual === 'object' ? task.actual : {}
  const prevDuration = Number(prev.durationMin) || 0
  const nextDuration = Number(activity.durationMin) || 0
  const totalDuration = prevDuration + nextDuration
  const weightedHr = totalDuration > 0
    ? Math.round(((Number(prev.avgHr) || 0) * prevDuration + (Number(activity.avgHr) || 0) * nextDuration) / totalDuration)
    : (Number(activity.avgHr) || Number(prev.avgHr) || 0)
  const ids = [...new Set([...(prev.activityIds || []), activity.id])]
  task.actual = sanitizeActual({
    distanceKm: (Number(prev.distanceKm) || 0) + (Number(activity.distanceKm) || 0),
    durationMin: totalDuration,
    avgHr: weightedHr,
    maxHr: Math.max(Number(prev.maxHr) || 0, Number(activity.maxHr) || 0),
    calories: (Number(prev.calories) || 0) + (Number(activity.calories) || 0),
    trainingLoad: (Number(prev.trainingLoad) || 0) + (Number(activity.trainingLoad) || 0),
    elevationGain: (Number(prev.elevationGain) || 0) + (Number(activity.elevationGain) || 0),
    elevationLoss: (Number(prev.elevationLoss) || 0) + (Number(activity.elevationLoss) || 0),
    avgPower: Number(activity.avgPower) || Number(prev.avgPower) || 0,
    normalizedPower: Number(activity.normalizedPower) || Number(prev.normalizedPower) || 0,
    sport: activity.sport || prev.sport || '',
    startTime: prev.startTime || activity.startTime || '',
    name: activity.name || prev.name || '',
    activityIds: ids
  })
}

export function applyActivities(state, incoming, options = {}) {
  const activities = Array.isArray(incoming) ? incoming : []
  const known = new Map(state.activities.map((activity) => [activity.id, activity]))
  let added = 0
  for (const raw of activities) {
    const activity = sanitizeActivity(raw)
    if (!activity) continue
    const existing = known.get(activity.id)
    if (existing) {
      const matchedTaskIds = [...new Set([...(existing.matchedTaskIds || []), ...activity.matchedTaskIds])]
      Object.assign(existing, activity, { id: existing.id, matchedTaskIds })
      continue
    }
    state.activities.unshift(activity)
    known.set(activity.id, activity)
    added += 1
  }
  state.activities.sort((a, b) => (b.date || '').localeCompare(a.date || ''))
  if (state.activities.length > MAX_ACTIVITIES) state.activities.length = MAX_ACTIVITIES

  let matched = 0
  for (const activity of state.activities) {
    const already = new Set(activity.matchedTaskIds || [])
    for (const task of state.tasks) {
      if (already.has(task.id)) continue
      if (!matchesTask(task, activity)) continue
      const delta = progressDelta(task, activity)
      task.progress.current = Math.round((task.progress.current + delta) * 100) / 100
      mergeActual(task, activity)
      task.updatedAt = nowIso()
      if (task.progress.target > 0 && task.progress.current >= task.progress.target) {
        task.completed = true
        task.completedAt = task.completedAt || nowIso()
      }
      activity.matchedTaskIds.push(task.id)
      already.add(task.id)
      matched += 1
    }
  }
  const autoTasks = applyGeneratedTasks(state, dateText(options.today) || todayText())
  recomputeParents(state.tasks)
  return { added, matched, autoTasks }
}

function descendantsOf(tasks, id) {
  const ids = new Set([id])
  let changed = true
  while (changed) {
    changed = false
    for (const task of tasks) {
      if (task.parentId && ids.has(task.parentId) && !ids.has(task.id)) {
        ids.add(task.id)
        changed = true
      }
    }
  }
  return ids
}

function findReview(reviews, review) {
  return reviews.find((row) => row.id === review.id)
    || reviews.find((row) => row.period === review.period && row.date === review.date)
}

export function applyOps(state, input) {
  const ops = Array.isArray(input) ? input.slice(0, 250) : []
  if (!ops.length) return { applied: 0 }
  let applied = 0
  for (const raw of ops) {
    if (!raw || typeof raw !== 'object') continue
    const type = String(raw.type || '')
    if (type === 'addTask') {
      const requestedParent = raw.task?.parentId ? String(raw.task.parentId).trim() : null
      const task = sanitizeTasks([raw.task])[0]
      if (!task) continue
      if (!state.tasks.some((row) => row.id === task.id)) {
        task.parentId = requestedParent && requestedParent !== task.id && state.tasks.some((row) => row.id === requestedParent)
          ? requestedParent
          : null
        state.tasks.push(task)
        applied += 1
      }
      continue
    }
    if (type === 'updateTask') {
      const task = state.tasks.find((row) => row.id === String(raw.id || ''))
      if (!task || !raw.patch || typeof raw.patch !== 'object') continue
      const patch = raw.patch
      const requestedParent = Object.prototype.hasOwnProperty.call(patch, 'parentId')
        ? (patch.parentId ? String(patch.parentId).trim() : null)
        : task.parentId
      const clean = sanitizeTasks([{
        ...task,
        ...patch,
        id: task.id,
        progress: { ...task.progress, ...(patch.progress || {}) },
        autoSync: { ...task.autoSync, ...(patch.autoSync || {}) }
      }])[0]
      if (!clean) continue
      if (patch.progress) {
        if (clean.progress.mode !== 'check' && clean.progress.target > 0 && clean.progress.current >= clean.progress.target) {
          clean.completed = true
          clean.completedAt = clean.completedAt || nowIso()
        } else if (clean.progress.mode !== 'check' && clean.progress.current < clean.progress.target) {
          clean.completed = false
          clean.completedAt = null
        }
      }
      clean.parentId = requestedParent && requestedParent !== clean.id && state.tasks.some((row) => row.id === requestedParent)
        ? requestedParent
        : null
      Object.assign(task, clean)
      if (task.autoGenerated) {
        task.completed = true
        task.completedAt = task.completedAt || nowIso()
        task.category = 'training'
      }
      applied += 1
      continue
    }
    if (type === 'deleteTask') {
      const rootId = String(raw.id || '')
      const root = state.tasks.find((task) => task.id === rootId)
      if (!root) continue
      if (root.autoGenerated) continue
      const ids = descendantsOf(state.tasks, rootId)
      for (const task of state.tasks) {
        if (ids.has(task.absorbedBy)) {
          task.absorbedBy = ''
          task.updatedAt = nowIso()
        }
      }
      state.tasks = state.tasks.filter((task) => !ids.has(task.id))
      applied += 1
      continue
    }
    if (type === 'toggleTask') {
      const ids = descendantsOf(state.tasks, String(raw.id || ''))
      const done = Boolean(raw.done)
      const when = nowIso()
      let changed = 0
      for (const other of state.tasks) {
        if (!done && ids.has(other.absorbedBy)) {
          other.absorbedBy = ''
          other.updatedAt = when
        }
      }
      for (const task of state.tasks) {
        if (!ids.has(task.id)) continue
        if (task.autoGenerated) {
          task.completed = true
          task.completedAt = task.completedAt || when
          task.updatedAt = when
          continue
        }
        task.completed = done
        task.completedAt = done ? when : null
        if (!done) task.mergedAt = ''
        if (done) {
          task.progress.current = task.progress.mode === 'check'
            ? 1
            : Math.max(task.progress.current, task.progress.target)
        } else if (task.progress.mode === 'check') {
          task.progress.current = 0
        }
        task.updatedAt = when
        changed += 1
      }
      if (changed) applied += 1
      continue
    }
    if (type === 'saveReview') {
      const review = sanitizeReviews([raw.review])[0]
      if (!review) continue
      const existing = findReview(state.reviews, review)
      if (existing) {
        Object.assign(existing, review, { id: existing.id, createdAt: existing.createdAt })
      } else {
        state.reviews.unshift(review)
      }
      applied += 1
      continue
    }
    if (type === 'deleteReview') {
      const review = findReview(state.reviews, {
        id: raw.id ? String(raw.id) : undefined,
        period: raw.period,
        date: raw.date
      })
      if (!review) continue
      state.reviews = state.reviews.filter((row) => row.id !== review.id)
      applied += 1
      continue
    }
    if (type === 'autoSync') {
      state.integrations.coros.autoSync = Boolean(raw.enabled)
      applied += 1
      continue
    }
    if (type === 'autoCreate') {
      const enabled = Boolean(raw.enabled)
      state.integrations.coros.autoCreateTasks = enabled
      if (enabled) state.integrations.coros.dismissedAutoTasks = []
      applied += 1
      continue
    }
    if (type === 'mergeBall') {
      const task = state.tasks.find((row) => row.id === String(raw.id || ''))
      if (!task) continue
      if (raw.merged === false) {
        task.mergedAt = ''
        for (const other of state.tasks) {
          if (other.absorbedBy === task.id) other.absorbedBy = ''
        }
        task.updatedAt = nowIso()
        applied += 1
        continue
      }
      const sourceId = String(raw.sourceTaskId || '')
      const source = sourceId ? state.tasks.find((row) => row.id === sourceId) : null
      if (source && source.id !== task.id && source.actual) {
        task.actual = source.actual
        source.absorbedBy = task.id
        source.updatedAt = nowIso()
      }
      task.completed = true
      task.completedAt = task.completedAt || nowIso()
      if (task.progress.mode === 'check') task.progress.current = 1
      else task.progress.current = Math.max(task.progress.current, task.progress.target)
      task.mergedAt = nowIso()
      task.updatedAt = nowIso()
      applied += 1
      continue
    }
    if (type === 'reorderTasks') {
      const ids = Array.isArray(raw.ids) ? raw.ids.map((id) => String(id || '')) : []
      const wanted = new Set(ids)
      let order = 0
      for (const id of ids) {
        const task = state.tasks.find((row) => row.id === id)
        if (task && !task.parentId) task.order = order++
      }
      for (const task of state.tasks) {
        if (!task.parentId && !wanted.has(task.id)) task.order = order++
      }
      applied += 1
    }
  }
  if (applied) {
    state.revision += 1
    state.updatedAt = nowIso()
    recomputeParents(state.tasks)
  }
  return { applied }
}
