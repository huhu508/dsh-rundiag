export async function loadState() {
  const file = stateFile()
  try {
    return normalizeState(JSON.parse(await readFile(file, 'utf8')))
  } catch (error) {
    if (error && error.code !== 'ENOENT') {
      console.warn('[dsh-rundiag] could not read state:', error.message)
    }
  }
  try {
    const backup = normalizeState(JSON.parse(await readFile(`${file}.bak`, 'utf8')))
    console.warn('[dsh-rundiag] recovered the previous state from the automatic backup')
    return backup
  } catch (backupError) {
    if (backupError && backupError.code !== 'ENOENT') {
      console.warn('[dsh-rundiag] could not read the automatic backup:', backupError.message)
    }
    return defaultState()
  }
}

export function normalizeState(raw) {
  const base = defaultState()
  const input = raw && typeof raw === 'object' ? raw : {}
  const tasks = sanitizeTasks(input.tasks)
  const taskIds = new Set(tasks.map((task) => task.id))
  const srcCoros = input.integrations?.coros || {}
  const dismissedAutoTasks = Array.isArray(srcCoros.dismissedAutoTasks)
    ? [...new Set(srcCoros.dismissedAutoTasks.map((key) => text(key, 160).trim()).filter(Boolean))].slice(-200)
    : []
  const activities = []
  const seenActivities = new Set()
  for (const item of Array.isArray(input.activities) ? input.activities : []) {
    const activity = sanitizeActivity(item)
    if (!activity || seenActivities.has(activity.id)) continue
    seenActivities.add(activity.id)
    activity.matchedTaskIds = activity.matchedTaskIds.filter((id) => taskIds.has(id))
    activities.push(activity)
    if (activities.length >= MAX_ACTIVITIES) break
  }
  const dailyMetrics = []
  const seenMetricDates = new Set()
  for (const item of Array.isArray(input.dailyMetrics) ? input.dailyMetrics : []) {
    const metric = sanitizeDailyMetric(item)
    if (!metric || seenMetricDates.has(metric.date)) continue
    seenMetricDates.add(metric.date)
    dailyMetrics.push(metric)
    if (dailyMetrics.length >= MAX_METRICS) break
  }
  dailyMetrics.sort((a, b) => a.date.localeCompare(b.date))
  return {
    version: 1,
    revision: Math.round(numberValue(input.revision, 0, 0, 1e12)),
    tasks,
    reviews: sanitizeReviews(input.reviews),
    activities,
    dailyMetrics,
    integrations: {
      coros: {
        region: ['cn', 'en', 'eu'].includes(srcCoros.region) ? srcCoros.region : base.integrations.coros.region,
        token: text(srcCoros.token, 4000),
        account: text(srcCoros.account, 300),
        name: text(srcCoros.name, 120),
        userId: text(srcCoros.userId, 120),
        connectedAt: srcCoros.connectedAt ? text(srcCoros.connectedAt, 40) : null,
        autoSync: bool(srcCoros.autoSync, true),
        autoCreateTasks: bool(srcCoros.autoCreateTasks, true),
        dismissedAutoTasks,
        lastSyncAt: srcCoros.lastSyncAt ? text(srcCoros.lastSyncAt, 40) : null,
        lastMetricsAt: srcCoros.lastMetricsAt ? text(srcCoros.lastMetricsAt, 40) : null,
        lastSyncError: srcCoros.lastSyncError ? text(srcCoros.lastSyncError, 800) : null
      }
    },
    updatedAt: text(input.updatedAt, 40) || base.updatedAt
  }
}

