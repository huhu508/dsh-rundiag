function text(value, max) {
  if (value === undefined || value === null) return ''
  return String(value).replace(/\u0000/g, '').slice(0, max)
}

function dateText(value) {
  const s = String(value || '').trim()
  return /^\d{4}-\d{2}-\d{2}$/.test(s) ? s : ''
}

function numberValue(value, fallback = 0, min = 0, max = 1e9) {
  const n = Number(value)
  if (!Number.isFinite(n)) return fallback
  return Math.min(max, Math.max(min, n))
}

function bool(value, fallback = false) {
  return typeof value === 'boolean' ? value : fallback
}

function sanitizeActual(raw) {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null
  const activityIds = Array.isArray(raw.activityIds)
    ? [...new Set(raw.activityIds.map((id) => text(id, 120)).filter(Boolean))].slice(0, 80)
    : []
  const actual = {
    distanceKm: Math.round(numberValue(raw.distanceKm, 0, 0, 10000) * 100) / 100,
    durationMin: Math.round(numberValue(raw.durationMin, 0, 0, 100000)),
    avgHr: Math.round(numberValue(raw.avgHr, 0, 0, 300)),
    maxHr: Math.round(numberValue(raw.maxHr, 0, 0, 300)),
    calories: Math.round(numberValue(raw.calories, 0, 0, 100000)),
    trainingLoad: Math.round(numberValue(raw.trainingLoad, 0, 0, 100000)),
    elevationGain: Math.round(numberValue(raw.elevationGain, 0, 0, 100000)),
    elevationLoss: Math.round(numberValue(raw.elevationLoss, 0, 0, 100000)),
    avgPower: Math.round(numberValue(raw.avgPower, 0, 0, 5000)),
    normalizedPower: Math.round(numberValue(raw.normalizedPower, 0, 0, 5000)),
    sport: SPORTS.has(raw.sport) ? raw.sport : '',
    startTime: text(raw.startTime, 40),
    name: text(raw.name, 200),
    activityIds
  }
  const hasMetric = actual.distanceKm || actual.durationMin || actual.calories || actual.trainingLoad
    || actual.avgHr || actual.elevationGain || actual.activityIds.length
  return hasMetric ? actual : null
}

export function sanitizeTasks(input) {
  if (!Array.isArray(input)) return []
  const rows = []
  const seen = new Set()
  for (let index = 0; index < input.length && rows.length < MAX_TASKS; index += 1) {
    const raw = input[index]
    if (!raw || typeof raw !== 'object') continue
    const title = text(raw.title, 400).trim()
    if (!title) continue
    let id = text(raw.id, 100).trim()
    if (!id || seen.has(id)) id = uid('task')
    seen.add(id)
    const mode = PROGRESS_MODES.has(raw.progress?.mode) ? raw.progress.mode : 'check'
    const unit = mode === 'distance' ? 'km' : mode === 'duration' ? '分钟' : mode === 'count' ? '次' : ''
    const tags = Array.isArray(raw.tags)
      ? [...new Set(raw.tags.map((tag) => text(tag, 32).trim()).filter(Boolean))].slice(0, 12)
      : []
    const autoGenerated = bool(raw.autoGenerated)
    const inferredCategory = autoGenerated || raw.autoSync?.enabled ? 'training' : 'other'
    const category = TASK_CATEGORIES.has(raw.category) ? raw.category : inferredCategory
    const createdAt = text(raw.createdAt, 40) || nowIso()
    const completed = bool(raw.completed)
    rows.push({
      id,
      title,
      notes: text(raw.notes, 20000),
      parentId: raw.parentId ? text(raw.parentId, 100) : null,
      dueDate: dateText(raw.dueDate),
      startDate: dateText(raw.startDate),
      priority: Math.round(numberValue(raw.priority, 2, 1, 4)),
      category,
      tags,
      completed,
      completedAt: completed ? (text(raw.completedAt, 40) || nowIso()) : null,
      mergedAt: completed ? text(raw.mergedAt, 40) : '',
      createdAt,
      updatedAt: text(raw.updatedAt, 40) || createdAt,
      order: numberValue(raw.order, index, -1e9, 1e9),
      progress: {
        mode,
        current: numberValue(raw.progress?.current, completed ? 1 : 0, 0, 1e9),
        target: numberValue(raw.progress?.target, 1, 1, 1e9),
        unit: text(raw.progress?.unit, 12) || unit
      },
      autoGenerated,
      absorbedBy: text(raw.absorbedBy, 100),
      actual: sanitizeActual(raw.actual),
      sourceKey: autoGenerated ? text(raw.sourceKey, 160) : '',
      sourceDate: autoGenerated ? dateText(raw.sourceDate) : '',
      sourceSport: autoGenerated && SPORTS.has(raw.sourceSport) ? raw.sourceSport : '',
      autoSync: {
        enabled: bool(raw.autoSync?.enabled),
        sport: SPORTS.has(raw.autoSync?.sport) ? raw.autoSync.sport : 'all',
        keyword: text(raw.autoSync?.keyword, 80)
      }
    })
  }

  const ids = new Set(rows.map((row) => row.id))
  for (const row of rows) {
    if (!row.parentId || row.parentId === row.id || !ids.has(row.parentId)) row.parentId = null
  }
  // Sever malformed parent cycles so recursive UI rendering can never loop.
  for (const row of rows) {
    const chain = new Set([row.id])
    let cursor = rows.find((candidate) => candidate.id === row.parentId)
    let depth = 0
    while (cursor && depth < 40) {
      if (chain.has(cursor.id)) {
        row.parentId = null
        break
      }
      chain.add(cursor.id)
      cursor = rows.find((candidate) => candidate.id === cursor.parentId)
      depth += 1
    }
  }
  return rows
}

